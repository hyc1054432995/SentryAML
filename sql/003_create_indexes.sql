-- ============================================================================
-- SentryAML - 003: 建索引
-- ============================================================================
-- 执行:
--   docker compose exec -T postgres psql -U sentry -d sentryaml -f /sql/003_create_indexes.sql
--
-- 必须在数据灌完之后执行。
-- 先建索引再灌数据的话，每插入一行都要维护所有索引，慢 3-10 倍。
-- 现在建，Postgres 可以一次性读出整列、排序、建树，效率高得多。
--
-- 建索引期间会用到 maintenance_work_mem（compose 里设成了 1GB），
-- 内存够大就能全程在内存里排序，不用落盘。
-- ============================================================================

\timing on


-- ============================================================================
-- 1. 出边索引 —— 图查询的核心
-- ============================================================================
-- 支撑的查询："这个账户转给了谁"
--     SELECT * FROM txn_edges WHERE from_bank = ? AND from_account = ?
--
-- 第三列 txn_ts 是刻意加的。反洗钱的核心问题几乎都带时间窗：
--     "X 在过去 24 小时内转给了哪些账户"  <- FAN-OUT 检测
--     "Y 在 7 天内从哪些账户收款"          <- FAN-IN 检测
-- 因为【最左前缀原则】，加了第三列之后：
--     - 只给前两列   -> 照样能用（退化成两列索引）
--     - 给三列       -> 时间范围也能在索引内部收敛，不用回表再过滤
-- 代价是索引大一些，换来时间窗查询不用二次筛选，划算。
-- ============================================================================
CREATE INDEX idx_txn_from
    ON transactions (from_bank, from_account, txn_ts);


-- ============================================================================
-- 2. 入边索引 —— 和上面对称
-- ============================================================================
CREATE INDEX idx_txn_to
    ON transactions (to_bank, to_account, txn_ts);


-- ============================================================================
-- 3. 时间索引（BRIN）
-- ============================================================================
-- BRIN = Block Range INdex，块范围索引。
-- 它不记录每一行的位置，只记录"第 1-128 个数据块里时间范围是 9/1 到 9/2"
-- 这样的粗粒度摘要。查时间区间时先排除掉范围不重叠的块。
--
-- 【前提】数据在物理上大致按该列有序。
-- 我们的交易是按时间顺序 COPY 进去的，完全符合。
-- 如果数据是乱序的，BRIN 等于没用——这是它唯一的限制。
--
-- 体积对比（508 万行）:
--     B-tree on txn_ts  约 110 MB
--     BRIN   on txn_ts  约  30 KB     <- 小三千多倍
-- 时间范围查询效果接近，所以这里选 BRIN。
--
-- pages_per_range=64: 每 64 个数据块记一个摘要（默认 128）。
-- 调小 -> 索引略大但更精确，能排除掉更多无关块。
-- ============================================================================
CREATE INDEX idx_txn_ts_brin
    ON transactions USING BRIN (txn_ts) WITH (pages_per_range = 64);


-- ============================================================================
-- 4. 洗钱交易部分索引
-- ============================================================================
-- WHERE 子句让索引【只包含满足条件的行】。
-- 全表 5,078,345 行里只有 5,177 行 is_laundering = 1，
-- 所以这个索引只有全表索引的千分之一大小。
--
-- 后面做标注、评测、模式分析时会反复取这批数据，
-- 这个索引几乎零成本地把它变成瞬时操作。
--
-- 注意：查询里的条件必须和索引定义的 WHERE 能对上，优化器才会用它。
-- 写 WHERE is_laundering = 1 能命中；写 WHERE is_laundering > 0 就不一定。
-- ============================================================================
CREATE INDEX idx_txn_laundering
    ON transactions (txn_ts, from_bank, from_account)
    WHERE is_laundering = 1;


-- ============================================================================
-- 5. 非自环部分索引 —— 加速 txn_edges 视图
-- ============================================================================
-- txn_edges 视图的定义是 WHERE NOT is_self_loop。
-- 这个部分索引和它的条件完全对应，优化器能识别并使用。
-- 449 万行 / 508 万行，过滤掉约 12%。
-- ============================================================================
CREATE INDEX idx_txn_edges_from
    ON transactions (from_bank, from_account, txn_ts)
    WHERE NOT is_self_loop;


-- ============================================================================
-- 6. accounts 按实体查
-- ============================================================================
-- 支撑："这个实体名下有哪些账户"——实体级图的基础。
-- 已知 63,362 个实体跨多家银行开户，这是 structuring 的关键信号。
-- ============================================================================
CREATE INDEX idx_accounts_entity
    ON accounts (entity_id);


-- ============================================================================
-- 7. 模式表索引
-- ============================================================================
CREATE INDEX idx_pattern_txn_id
    ON pattern_transactions (txn_id)
    WHERE txn_id IS NOT NULL;

CREATE INDEX idx_patterns_type
    ON laundering_patterns (pattern_type);


-- ============================================================================
-- 【刻意不建的索引】及理由
-- ============================================================================
-- entities(entity_type)  —— 只有 6 个不同取值（Corporation/Partnership/...），
--     这叫【低选择性】。查 entity_type='Corporation' 会命中三分之一的行，
--     走索引反而比全表扫描慢（因为要先查索引、再逐行回表）。
--     经验法则：一个条件筛掉不到 90% 的行，索引通常不划算。
--
-- transactions(payment_format) —— 同理，7 个取值。
--
-- transactions(currency_paid)  —— 15 个取值，且 US Dollar 一家占 37%。
--
-- 这些列真要频繁查，正确做法是把它们【组合】进其他索引，
-- 或者用部分索引锁定某个稀有取值，而不是单独建。
-- ============================================================================


-- ============================================================================
-- 更新统计信息
-- ============================================================================
-- 建完索引必须重新 ANALYZE：优化器要知道新索引的存在和数据分布，
-- 才会在执行计划里考虑使用它们。
-- ============================================================================
ANALYZE transactions;
ANALYZE accounts;
ANALYZE entities;
ANALYZE banks;

\timing off


-- ============================================================================
-- 查看结果
-- ============================================================================
\echo ''
\echo '=== 索引清单与体积 ==='

SELECT
    tablename                                        AS "表",
    indexname                                        AS "索引",
    pg_size_pretty(pg_relation_size(indexrelid))     AS "大小"
FROM pg_stat_user_indexes
JOIN pg_indexes
  ON pg_indexes.indexname = pg_stat_user_indexes.indexrelname
ORDER BY pg_relation_size(indexrelid) DESC;

\echo ''
\echo '=== 表与索引总体积 ==='

SELECT
    relname                                            AS "表",
    pg_size_pretty(pg_table_size(relid))               AS "表数据",
    pg_size_pretty(pg_indexes_size(relid))             AS "索引",
    pg_size_pretty(pg_total_relation_size(relid))      AS "合计"
FROM pg_stat_user_tables
ORDER BY pg_total_relation_size(relid) DESC;